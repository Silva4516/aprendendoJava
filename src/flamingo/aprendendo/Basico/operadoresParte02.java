package flamingo.aprendendo.Basico;

public class operadoresParte02 {
    /*
    * < menor que
    * > maior que
    * <= menor ou igual
    * >= maior ou igual
    * == igual a
    * != diferente de
     */

    public static void main(String[] args) {
        int numero01  = 10;
        int numero02 = 20;


        System.out.println( numero01 < numero02 );
        System.out.println(numero01 > numero02);
        System.out.println(numero01<= numero02);
        System.out.println(numero01>= numero02);
        System.out.println(numero01<= numero02);
        System.out.println(numero01 == numero02);
        System.out.println(numero01 != numero02);







    }
}
